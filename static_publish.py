"""
把 Crew 产出的 Markdown 写成 site/ 下的静态 HTML，供本地预览或 GitHub Pages。
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from html import escape
from pathlib import Path
from typing import Any, Optional

_REPO_ROOT = Path(__file__).resolve().parent
# GitHub Pages「从分支部署」只支持 / 或 /docs，故静态站落在 docs/
_DEFAULT_SITE_DIR = _REPO_ROOT / "docs"


def _result_to_markdown(result: Any) -> str:
    if result is None:
        return ""
    raw = getattr(result, "raw", None)
    if raw:
        return str(raw).strip()
    return str(result).strip()


def _slugify(text: str, max_len: int = 48) -> str:
    text = text.strip().lower()
    text = re.sub(r"\s+", "-", text)
    text = re.sub(r"[^a-z0-9\-一-龥]+", "", text)
    text = re.sub(r"-{2,}", "-", text).strip("-")
    return (text or "post")[:max_len]


def _extract_title(markdown: str, fallback: str) -> str:
    for line in markdown.splitlines():
        s = line.strip()
        if s.startswith("# "):
            return s[2:].strip() or fallback
    return fallback


def _markdown_to_html_body(markdown: str) -> str:
    try:
        import markdown as md

        return md.markdown(
            markdown,
            extensions=["extra", "sane_lists", "nl2br"],
        )
    except ImportError:
        # 无 markdown 包时的兜底：整块转义 + 换行
        return "<pre class=\"md-fallback\">" + escape(markdown) + "</pre>"


def _page_shell(title: str, body_html: str, *, relative_css: str = "../assets/style.css") -> str:
    safe_title = escape(title)
    return f"""<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>{safe_title}</title>
  <link rel="stylesheet" href="{relative_css}" />
</head>
<body>
  <header class="site-header">
    <a href="../index.html">SEO Agent 静态站</a>
  </header>
  <main class="post">
    <article>
{body_html}
    </article>
  </main>
  <footer class="site-footer">
    <p>Generated by seo-agent · <a href="https://yibelin.com">yibelin.com</a></p>
  </footer>
</body>
</html>
"""


def _rebuild_index(site_dir: Path) -> Path:
    posts_dir = site_dir / "posts"
    posts = sorted(posts_dir.glob("*.html"), reverse=True)
    items = []
    for p in posts:
        if p.name.startswith("_"):
            continue
        # 从文件名粗提标题；页面内再有完整 H1
        label = p.stem
        items.append(f'      <li><a href="posts/{escape(p.name)}">{escape(label)}</a></li>')

    listing = "\n".join(items) if items else "      <li>（暂无文章）</li>"
    html = f"""<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>SEO Agent 静态站</title>
  <link rel="stylesheet" href="assets/style.css" />
</head>
<body>
  <header class="site-header">
    <strong>SEO Agent 静态站</strong>
  </header>
  <main class="index">
    <h1>文章列表</h1>
    <ul class="post-list">
{listing}
    </ul>
  </main>
  <footer class="site-footer">
    <p>Generated by seo-agent</p>
  </footer>
</body>
</html>
"""
    index_path = site_dir / "index.html"
    index_path.write_text(html, encoding="utf-8")
    return index_path


def publish_static_page(
    result: Any,
    *,
    seed_keyword: str = "post",
    site_dir: Optional[Path] = None,
) -> Path:
    """
    将一次流水线结果写成 site/posts/<timestamp>-<slug>.html，并刷新 index.html。
    返回文章 HTML 路径。
    """
    site_dir = Path(site_dir) if site_dir else _DEFAULT_SITE_DIR
    posts_dir = site_dir / "posts"
    assets_dir = site_dir / "assets"
    posts_dir.mkdir(parents=True, exist_ok=True)
    assets_dir.mkdir(parents=True, exist_ok=True)

    markdown = _result_to_markdown(result)
    title = _extract_title(markdown, fallback=seed_keyword)
    body = _markdown_to_html_body(markdown)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    slug = _slugify(seed_keyword)
    filename = f"{stamp}-{slug}.html"
    out_path = posts_dir / filename
    out_path.write_text(_page_shell(title, body), encoding="utf-8")

    # 同步保存原始 Markdown，方便 diff / 再加工
    md_path = posts_dir / f"{stamp}-{slug}.md"
    md_path.write_text(markdown + "\n", encoding="utf-8")

    _rebuild_index(site_dir)
    return out_path
